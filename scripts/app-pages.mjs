// Writes public/<app id>/index.html for each featured app, from src/apps.js.
// Runs before every build (npm "prebuild"). Hand-made pages (AirReply's and
// ArtSuite's download pages) are left alone: a page is only (re)written when it
// is missing or carries the GENERATED marker.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { APPS } from '../src/apps.js';

const SITE = 'https://www.customfusion.co';
const GENERATED = '<!-- generated by scripts/app-pages.mjs; edit src/apps.js instead -->';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function shot(s, name) {
  return `<div class="shot shot-${s.kind}"><img src="${s.src}" alt="${esc(name)} screenshot" loading="lazy"></div>`;
}

function page(app) {
  const others = APPS.filter((a) => a.id !== app.id);
  const title = `${app.name}: ${app.tagline.replace(/\.$/, '')} | Custom Fusion`;
  const og = existsSync(`public/og/${app.id}.png`) ? `${SITE}/og/${app.id}.png` : `${SITE}/og.png`;
  return `<!doctype html>
${GENERATED}
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(app.description)}">
  <meta name="theme-color" content="#050505">
  <link rel="canonical" href="${SITE}/${app.id}/">
  <link rel="icon" href="${app.icon}">
  <meta property="og:type" content="website">
  <meta property="og:url" content="${SITE}/${app.id}/">
  <meta property="og:title" content="${esc(app.name)}: ${esc(app.tagline)}">
  <meta property="og:description" content="${esc(app.description)}">
  <meta property="og:image" content="${og}">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="${og}">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600&family=Orbitron:wght@700&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="/app-page.css">
  <script defer src="/_vercel/insights/script.js"></script>
</head>
<body style="--accent: ${app.accent}">
  <nav class="bar">
    <a href="/" class="logo"><img src="/logo.png" alt="">Custom&nbsp;<span>Fusion</span></a>
    <a href="/#apps" class="all">All apps</a>
  </nav>
  <main>
    <header class="hero">
      <img src="${app.icon}" alt="${esc(app.name)} icon" class="icon">
      <h1>${esc(app.name)}</h1>
      <p class="tagline">${esc(app.tagline)}</p>
      <p class="desc">${esc(app.description)}</p>
      <a href="${app.href}" class="cta">${esc(app.cta)}</a>
      <p class="status">${esc(app.status)} · ${app.platforms.map(esc).join(' · ')}</p>
    </header>
    ${app.shots.length ? `<section class="shots">${app.shots.map((s) => shot(s, app.name)).join('')}</section>` : ''}
    <ul class="points">${app.points.map((p) => `<li>${esc(p)}</li>`).join('')}</ul>
    <p class="note">Shown with sample data. Questions or ideas: <a href="mailto:julian@customfusion.co">julian@customfusion.co</a></p>
    <section class="more">
      <h2>More free apps</h2>
      <div class="dock">${others.map((a) => `<a href="/${a.id}/"><img src="${a.icon}" alt=""><span>${esc(a.name)}</span></a>`).join('')}</div>
    </section>
  </main>
  <footer>© ${new Date().getFullYear()} Custom Fusion Inc. · New York</footer>
</body>
</html>
`;
}

let wrote = 0;
for (const app of APPS) {
  const file = `public/${app.id}/index.html`;
  if (existsSync(file) && !readFileSync(file, 'utf8').includes(GENERATED)) continue; // hand-made page
  mkdirSync(`public/${app.id}`, { recursive: true });
  writeFileSync(file, page(app));
  wrote++;
}

// Sitemap lists the home page and every app page.
writeFileSync('public/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${SITE}/</loc></url>
${APPS.filter((a) => !readFileSync(`public/${a.id}/index.html`, 'utf8').includes('noindex')).map((a) => `  <url><loc>${SITE}/${a.id}/</loc></url>`).join('\n')}
</urlset>
`);

console.log(`app-pages: wrote ${wrote} app pages and sitemap.xml`);
